#!/usr/bin/env node
// Generates the Swift copies of spectra-lab's reference tables:
//
//   Spectra/Core/Data/XCOMTables.swift       from spectra-lab/src/data/xcom.js
//   Spectra/Core/Data/SegelsteinWater.swift  from spectra-lab/src/data/water.js
//
//   node Tools/gen-tables.mjs                 # writes both files
//   node Tools/gen-tables.mjs --check         # exits 1 if either file is stale
//   SPECTRA_LAB=/path/to/spectra-lab node Tools/gen-tables.mjs
//
// Every number is written with JS String(n) (shortest round trip), so the Swift literal parses
// to the same double bit for bit. Keep the raw values: Segelstein's long-wavelength rows carry
// float32 artefacts from the source file (3899000064, 4698999808, ...) and "cleaning" them would
// move the table knots. XCOM edges are repeated energies, below-edge row first.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const project = resolve(here, "..");
const lab = resolve(process.env.SPECTRA_LAB ?? join(project, "..", "spectra-lab"));
const outDir = join(project, "Spectra", "Core", "Data");

const { XCOM } = await import(pathToFileURL(join(lab, "src/data/xcom.js")).href);
const { WATER_ABSORPTION } = await import(pathToFileURL(join(lab, "src/data/water.js")).href);

const num = (n) => {
  if (!Number.isFinite(n)) throw new Error(`non-finite table value ${n}`);
  return String(n);
};
// Flattened [x0, y0, x1, y1, ...] literal, eight pairs per line.
function flatLiteral(rows, indent) {
  const lines = [];
  for (let i = 0; i < rows.length; i += 8) {
    lines.push(indent + rows.slice(i, i + 8).map(([x, y]) => `${num(x)}, ${num(y)}`).join(", ") + ",");
  }
  return lines.join("\n");
}
const swiftString = (s) => JSON.stringify(s); // plain ASCII names and URLs; JSON escaping is valid Swift

const header = (from) => `// GENERATED by Tools/gen-tables.mjs from spectra-lab/${from}. Do not edit.
// Regenerate with \`node Tools/gen-tables.mjs\`; \`node Tools/gen-tables.mjs --check\` reports staleness.
`;

// ---------------------------------------------------------------------------------- XCOM
const materials = Object.entries(XCOM);
let xcom = header("src/data/xcom.js") + `
import Foundation

/// The six materials with NIST XCOM mass attenuation tables (Hubbell & Seltzer, NISTIR 5632,
/// retrieved 2026-10-03). Rows are [photon energy MeV, μ/ρ cm²/g]; repeated energies mark
/// absorption edges (below-edge value first). TABLE provenance.
nonisolated enum XCOMMaterial: String, CaseIterable, Codable, Sendable {
${materials.map(([k]) => `  case ${k}`).join("\n")}

  /// NIST material name.
  var name: String {
    switch self {
${materials.map(([k, v]) => `    case .${k}: ${swiftString(v.name)}`).join("\n")}
    }
  }

  /// Default density, g/cm³ (used by \`Matter.linearAttenuation\`).
  var density: Double {
    switch self {
${materials.map(([k, v]) => `    case .${k}: ${num(v.density)}`).join("\n")}
    }
  }

  /// NIST page the table was taken from.
  var sourceURL: String {
    switch self {
${materials.map(([k, v]) => `    case .${k}: ${swiftString(v.source)}`).join("\n")}
    }
  }

  /// The [MeV, cm²/g] table as a log-log interpolation table.
  var table: LogLogTable {
    switch self {
${materials.map(([k]) => `    case .${k}: XCOMTables.${k}Table`).join("\n")}
    }
  }
}

/// Flattened XCOM rows, [MeV, cm²/g, MeV, cm²/g, ...].
nonisolated enum XCOMTables {
${materials.map(([k, v]) => `  /// ${v.name}: ${v.rows.length} rows.
  static let ${k}: [Double] = [
${flatLiteral(v.rows, "    ")}
  ]
  static let ${k}Table = LogLogTable(flat: ${k})`).join("\n\n")}
}
`;

// ---------------------------------------------------------------------------------- Segelstein
const water = header("src/data/water.js") + `
import Foundation

/// Liquid water absorption coefficient: D. J. Segelstein, "The complex refractive index of water",
/// M.S. thesis, University of Missouri-Kansas City (1981), via https://omlc.org/spectra/water/
/// (retrieved 2026-10-03). TABLE provenance.
nonisolated enum SegelsteinWater {
  /// [vacuum wavelength nm, α 1/cm] pairs, flattened. ${WATER_ABSORPTION.length} rows, 10 nm to 10 m.
  static let flat: [Double] = [
${flatLiteral(WATER_ABSORPTION, "    ")}
  ]
  /// \`flat\` split into knots once (a lazily initialized, thread-safe static).
  static let table = LogLogTable(flat: flat)
}
`;

const outputs = [
  [join(outDir, "XCOMTables.swift"), xcom],
  [join(outDir, "SegelsteinWater.swift"), water],
];
if (process.argv.includes("--check")) {
  let stale = false;
  for (const [path, text] of outputs) {
    let existing = "";
    try { existing = readFileSync(path, "utf8"); } catch { /* missing counts as stale */ }
    if (existing !== text) { console.error(`stale: ${path}`); stale = true; }
  }
  if (stale) { console.error("run: node Tools/gen-tables.mjs"); process.exit(1); }
  console.log(`tables current (${materials.length} XCOM materials, ${WATER_ABSORPTION.length} Segelstein rows)`);
} else {
  for (const [path, text] of outputs) { writeFileSync(path, text); console.log(`wrote ${path}`); }
}
